#!/usr/bin/env bash
#
# update_locks.sh - regenerate the explicit conda lock files from environment.yml.
#
# The lock files pin every package (including Python and all transitive dependencies)
# to an exact build, URL and md5, so `-profile conda` and the Docker image install the
# same environment everywhere and at any later date. environment.yml stays the
# human-edited source; re-run this script after changing it and commit the results.
#
# Requires micromamba (or mamba) on PATH. Usage: conda-lock/update_locks.sh [platform ...]

set -euo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ENV_FILE="$HERE/../environment.yml"
PLATFORMS=("$@")
[[ ${#PLATFORMS[@]} -gt 0 ]] || PLATFORMS=(linux-64 linux-aarch64 osx-64 osx-arm64)

SOLVER="$(command -v micromamba || command -v mamba || true)"
[[ -n "$SOLVER" ]] || { echo "error: micromamba or mamba is required" >&2; exit 1; }
export MAMBA_ROOT_PREFIX="${MAMBA_ROOT_PREFIX:-$(mktemp -d)}"
trap 'rm -f "$HERE/.solve.json"' EXIT

# Solve against fixed system baselines instead of whatever machine runs this script:
# glibc 2.28 (conda-forge's Linux baseline, RHEL/Rocky 8 and newer) and macOS 11.
export CONDA_OVERRIDE_GLIBC="${CONDA_OVERRIDE_GLIBC:-2.28}"
export CONDA_OVERRIDE_OSX="${CONDA_OVERRIDE_OSX:-11.0}"

for platform in "${PLATFORMS[@]}"; do
  echo ">>> solving $ENV_FILE for $platform (glibc $CONDA_OVERRIDE_GLIBC / macOS $CONDA_OVERRIDE_OSX)"
  "$SOLVER" create --name msa-lock --platform "$platform" --file "$ENV_FILE" \
      --dry-run --json --yes > "$HERE/.solve.json"
  python3 - "$HERE/.solve.json" "$platform" "$HERE/environment.$platform.txt" <<'PY'
import json, os, sys
solve, platform, out = sys.argv[1:]
packages = sorted(json.load(open(solve))['actions']['LINK'], key=lambda p: p['name'])
with open(out, 'w') as f:
    f.write('# Explicit lock of environment.yml for MSA - generated by conda-lock/update_locks.sh, do not edit.\n')
    f.write(f'# platform: {platform}\n')
    f.write(f"# system baseline: glibc {os.environ['CONDA_OVERRIDE_GLIBC']} / macOS {os.environ['CONDA_OVERRIDE_OSX']}\n")
    f.write('# Create the env with: conda create --name msa --file <this file>  (or micromamba/mamba)\n')
    f.write('@EXPLICIT\n')
    for p in packages:
        f.write(f"{p['url']}#{p['md5']}\n")
print(f'    {len(packages)} packages -> {out}')
PY
done

